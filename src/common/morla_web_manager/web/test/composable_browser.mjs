/** Real headless browser E2E against an isolated standalone composable API.
 * Start create_app with temporary store/resource_root, build web/dist, then:
 * NODE_PATH=<bundled node_modules> node test/composable_browser.mjs
 * BASE_URL and BROWSER_EXECUTABLE may override the defaults. No real backend is started.
 */
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require('playwright')
const base = process.env.BASE_URL || 'http://127.0.0.1:18082'
const output = process.env.BROWSER_OUTPUT || '/tmp/morla-composable-browser'
fs.mkdirSync(output, { recursive: true })
const bundled = chromium.executablePath()
const executable = process.env.BROWSER_EXECUTABLE || (fs.existsSync(bundled) ? bundled : '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge')
const browser = await chromium.launch({ executablePath: executable, headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const page = await context.newPage()
const errors = [], checks = [], responses = []
page.on('pageerror', error => errors.push(error.message))
page.on('response', response => { if (response.url().includes('/api/v2/')) responses.push({ url: response.url(), status: response.status() }) })
const label = text => page.getByLabel(text, { exact: true })
const button = text => page.getByRole('button', { name: text, exact: true })
const message = page.getByTestId('compose-message')
const waitMessage = text => message.filter({ hasText: text }).waitFor()
async function add(id, plugin) { await label('实例名称').fill(id); await label('组件').selectOption(plugin); await button('添加组件').click(); await label(id + '运行后端').waitFor() }
async function compile() { await button('校验并预览').click(); await waitMessage('配置校验通过') }
try {
  await page.goto(base)
  await page.getByRole('heading', { name: '组合机器人系统' }).waitFor()
  await label('组件').selectOption('morla.nero.arm')
  await label('配置名称').fill('browser_' + Date.now())
  await add('left_arm', 'morla.nero.arm'); await label('left_arm安装侧').selectOption('left')
  await add('right_arm', 'morla.astral.arm'); await label('right_arm安装侧').selectOption('right')
  await add('tool', 'morla.astral.gripper'); await label('tool安装侧').selectOption('right')
  await add('camera', 'morla.fake.camera')
  await add('phone', 'morla.input.mobile')
  await add('pad', 'morla.input.xbox')
  checks.push('descriptor-driven component/backend/side forms')
  await label('right_arm运行后端').selectOption('sim')
  await compile()
  assert.match(await page.getByText('组件后端声明可用：', { exact: false }).innerText(), /false/)
  await label('right_arm运行后端').selectOption('fake')
  await page.getByText('安装关系与部署配置', { exact: true }).click()
  await label('部署配置').fill('{")invalid')
  await button('应用部署配置').click()
  assert.equal(await label('部署配置').inputValue(), '{")invalid')
  await label('部署配置').fill(JSON.stringify({ instances: { left_arm: { device_id: 'review-only', verified: false, stop_verified: false } } }))
  await button('应用部署配置').click()
  await label('left_arm运行后端').selectOption('real')
  await compile()
  assert.match(await page.getByText('组件后端声明可用：', { exact: false }).innerText(), /部署核验通过：false/)
  await button('部署预检').click(); await waitMessage('部署预检返回')
  await page.getByRole('heading', { name: '部署预检结果' }).waitFor()
  checks.push('real selection remains unverified; independent deployment/preflight result')
  await label('left_arm运行后端').selectOption('fake')
  await label('部署配置').fill('{}'); await button('应用部署配置').click()
  await button('添加绑定').click()
  await label('binding_1输入端口').selectOption('phone.axes')
  await label('binding_1控制目标').selectOption('right_arm.joint_target')
  await label('binding_1按住控制').selectOption('phone.hold_to_control')
  await label('binding_1映射方式').selectOption('morla.joint_jog')
  assert.equal(await label('binding_1按住控制').locator('option[value="pad.deadman"]').count(), 0)
  const mapping = { axes_map: ['x', null, null, null, null, null, null], speed: .25 }
  await label('binding_1映射参数').fill('{"speed":')
  await button('应用binding_1映射参数').click()
  assert.equal(await label('binding_1映射参数').inputValue(), '{"speed":')
  await label('binding_1映射参数').fill(JSON.stringify(mapping)); await button('应用binding_1映射参数').click()
  checks.push('capability/deadman selectors and invalid JSON drafts retained')
  await label('观测left_arm.velocity').check()
  await label('动作tool.closure').uncheck()
  await label('camera.rgb数据键').fill('overhead_custom'); await label('camera.rgb数据键').blur()
  await compile()
  assert.match(await page.getByTestId('contract-dimensions').innerText(), /观测 22 维 · 动作 14 维 · 相机 1 路/)
  await page.getByText('完整装配配置', { exact: true }).click()
  await label('完整装配配置').fill('{}'); await button('载入编辑配置').click()
  assert.equal(await label('完整装配配置').inputValue(), '{}')
  await waitMessage('装配需要合法')
  await page.getByRole('heading', { name: '组合机器人系统' }).waitFor()
  await button('导出到编辑区').click()
  await compile()
  await page.screenshot({ path: path.join(output, 'forms.png'), fullPage: true })
  checks.push('mixed-brand independent state/action projection and camera dataset key')
  await button('保存下一版本').click(); await waitMessage('已保存不可变版本 v1')
  await label('观测left_arm.velocity').uncheck(); await compile()
  assert.equal(await button('启动已保存版本').isDisabled(), true)
  await label('观测left_arm.velocity').check(); await compile()
  await button('启动已保存版本').click()
  await page.getByTestId('session-status').filter({ hasText: 'READY_DISARMED' }).waitFor()
  await button('激活运动许可').click()
  await page.getByTestId('session-status').filter({ hasText: 'ACTIVE' }).waitFor()
  await button('开始采集').click(); await waitMessage('episode_dir')
  await page.waitForTimeout(350)
  await page.route('**/api/v2/sessions/*/recordings/stop', async route => { await new Promise(resolve => setTimeout(resolve, 200)); await route.continue() })
  await button('结束保存').click()
  assert.equal(await button('急停').isEnabled(), true)
  await waitMessage('status')
  await page.unroute('**/api/v2/sessions/*/recordings/stop')
  // No motion command was dispatched, so command-supervised recording must be failed, not mislabeled complete.
  assert.match(await message.innerText(), /failed/)
  checks.push('saved revision/start/activation and honest incomplete-recording status')
  await button('急停').click(); await page.getByTestId('session-status').filter({ hasText: 'ESTOP_LATCHED' }).waitFor()
  await button('复位故障').click(); await page.getByTestId('session-status').filter({ hasText: 'READY_DISARMED' }).waitFor()
  await button('停止会话').click(); await page.getByTestId('session-status').filter({ hasText: 'STOPPED' }).waitFor()
  await page.screenshot({ path: path.join(output, 'stopped.png'), fullPage: true })
  checks.push('emergency stop, explicit reset and stop lifecycle from actual buttons')
  assert.deepEqual(errors, [])
  const result = { success: true, checks, pageErrors: errors, apiResponses: responses, screenshots: ['forms.png', 'stopped.png'] }
  fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(result, null, 2))
  console.log(JSON.stringify({ success: true, checks, output }, null, 2))
} catch (error) {
  await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {})
  fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify({ success: false, checks, pageErrors: errors, apiResponses: responses, error: String(error) }, null, 2))
  throw error
} finally { await context.close(); await browser.close() }
