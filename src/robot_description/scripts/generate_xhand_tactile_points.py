#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""generate_tactile_points.py — 把 XHAND1 的触觉测点阵内嵌进 URDF。

背景
----
XHAND1 每个指尖有一片 120 点三轴触觉阵列：拇指用 T30，其余四指用 T16。
厂商给的三份 `*_transformed.json` 里，测点坐标**已经在 URDF 中各指 link2 坐标系**下，
单位 **mm**（已核对：120/120 点都贴在对应 link2 网格表面，max < 1.2mm）。

本脚本把测点写成 URDF 的 1200 个 link/joint 对，原地写回 URDF：
  - 每点一个 link —— Isaac Lab 用 `merge_fixed_joints=False` 导入后可逐 prim 挂
    ContactSensor 做逐点触觉；
  - 每点一个**命名** collision 球 —— MuJoCo 的 geom 名取自 `<collision name="...">`，
    逐点接触力就是靠这个名字从 `data.contact` 里认出来的；
  - 每点一个 visual 球 —— 只为 RViz 看得见（MuJoCo 默认丢弃 visual，不影响仿真）；
  - fixed joint 挂到各指 link2。

幂等
----
生成内容用 `<!-- TACTILE-BEGIN ... --> ... <!-- TACTILE-END -->` 包裹，
每次重跑先删旧块再重建；`--remove-tactile` 可一键还原成厂商原文件。

用法
----
  python3 scripts/generate_tactile_points.py                  # 生成（r=0.5mm，含 visual）
  python3 scripts/generate_tactile_points.py --no-visual      # 不写 visual（给 RViz 减负）
  python3 scripts/generate_tactile_points.py --radius 0.3     # 改探针球半径（mm）
  python3 scripts/generate_tactile_points.py --proud 0.15     # 沿表面法线外凸（mm）
  python3 scripts/generate_tactile_points.py --remove-tactile # 还原
  python3 scripts/generate_tactile_points.py --dry-run        # 只统计，不落盘

命名约定（也是仿真侧认点的依据）
----
  link      : <side>_hand_<finger>_tac_p###      （### = JSON 里的 point，1..120）
  joint     : <side>_hand_<finger>_tac_joint_p###
  collision : tac_<side>_<finger>_p###           （= MuJoCo geom 名）
  <side>   ∈ {left, right}；<finger> ∈ {thumb, index, mid, ring, pinky}

  SDK 侧每指尖的 `raw_force[120]`（0 基）对应这里的 point = k+1。
  ⚠ 该序号对应关系厂商文档未明示，首次上实机请单点按压验证一次。
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

BEGIN = "  <!-- TACTILE-BEGIN : generated by scripts/generate_tactile_points.py — 勿手改 -->"
END = "  <!-- TACTILE-END -->"

PKG_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_URDF = PKG_ROOT / "urdf" / "nero" / "xhand_nero_description.urdf"

SIDES = ("left", "right")
FINGERS = ("thumb", "index", "mid", "ring", "pinky")

# 各指 link2 的 link 名（T16/T30 测点就是这两个坐标系下的）
PARENT_LINK = {
    "thumb": "{side}_hand_thumb_rota_link2",
    "index": "{side}_hand_index_rota_link2",
    "mid": "{side}_hand_mid_link2",
    "ring": "{side}_hand_ring_link2",
    "pinky": "{side}_hand_pinky_link2",
}

# 各指 link2 的网格文件名（只给 --proud > 0 时算法线用）
PARENT_MESH = {
    "thumb": "{side}_hand_thumb_rota_link2.stl",
    "index": "{side}_hand_index_rota_link2.stl",
    "mid": "{side}_hand_mid_link2.stl",
    "ring": "{side}_hand_ring_link2.stl",
    "pinky": "{side}_hand_pinky_link2.stl",
}

T16_FILE = "points_t16_transformed+(1).json"
T30_FILE = {"left": "points_t30_left_hand_transformed.json",
            "right": "points_t30_right_hand_transformed.json"}


def points_file(side: str, finger: str) -> str:
    """拇指用 T30（左右各一份），其余四指共用 T16（左右手 link2 网格同构）。"""
    return T30_FILE[side] if finger == "thumb" else T16_FILE


# --------------------------------------------------------------------------- #
# 读取测点
# --------------------------------------------------------------------------- #
def load_points(path: Path):
    """→ [(idx, x_mm, y_mm, z_mm), ...]，按 JSON 里的 point 号升序。"""
    data = json.loads(path.read_text(encoding="utf-8"))
    pts = sorted(data["measurement_points"], key=lambda p: p["point"])
    return [(int(p["point"]), float(p["x"]), float(p["y"]), float(p["z"])) for p in pts]


# --------------------------------------------------------------------------- #
# 表面法线（只在 --proud > 0 时用到，按需求再 import numpy）
# --------------------------------------------------------------------------- #
def surface_normals(stl_path: Path, points):
    """对每个点找最近的网格三角形，返回朝外的单位法线。

    STL 面法线的朝向不保证；用「背离网格质心」来判内外 —— 指尖是凸形，够用。
    """
    import struct
    import numpy as np
    from scipy.spatial import cKDTree

    with open(stl_path, "rb") as f:
        f.read(80)
        n = struct.unpack("<I", f.read(4))[0]
        raw = np.frombuffer(f.read(n * 50), dtype=np.uint8).reshape(n, 50)
        tris = raw[:, 12:48].copy().view("<f4").reshape(n, 3, 3).astype(np.float64) * 1000.0

    v0, v1, v2 = tris[:, 0], tris[:, 1], tris[:, 2]
    normals = np.cross(v1 - v0, v2 - v0)
    ln = np.linalg.norm(normals, axis=1, keepdims=True)
    normals = normals / np.where(ln == 0, 1.0, ln)

    # 面上密采样，把「采样点 → 所属三角形」一起带走
    rng = np.random.default_rng(0)
    k = 8
    r1 = np.sqrt(rng.random((len(tris), k)))
    r2 = rng.random((len(tris), k))
    samples = ((1 - r1)[..., None] * v0[:, None, :]
               + (r1 * (1 - r2))[..., None] * v1[:, None, :]
               + (r1 * r2)[..., None] * v2[:, None, :]).reshape(-1, 3)
    tri_of_sample = np.repeat(np.arange(len(tris)), k)

    tree = cKDTree(samples)
    P = np.array(points, dtype=np.float64)
    _, idx = tree.query(P)
    face = normals[tri_of_sample[idx]]

    centroid = (v0.mean(0) + v1.mean(0) + v2.mean(0)) / 3.0
    outward = P - centroid
    sign = np.sign((face * outward).sum(axis=1))
    sign[sign == 0] = 1.0
    return face * sign[:, None]


# --------------------------------------------------------------------------- #
# 生成 / 剥离
# --------------------------------------------------------------------------- #
def fmt(v: float) -> str:
    s = f"{v:.9g}"
    return "0" if s in ("-0", "-0.0") else s


def build_block(json_dir: Path, radius_mm: float, proud_mm: float,
                density: float | None, with_visual: bool) -> str:
    r = radius_mm / 1000.0
    out = [BEGIN,
           "  <!-- 1200 个触觉测点：每点一个 link + fixed joint 挂到各指 link2。",
           "       来源 points_t16_transformed / points_t30_{left,right}_hand_transformed.json",
           f"       探针球半径 {radius_mm} mm，外凸 {proud_mm} mm，" + (
               f"按密度 {density} kg/m³ 显式给惯量。"
               if density else
               "不写 <inertial> —— 由仿真器按球体几何推导质量（MuJoCo 默认密度 1000）。"),
           "       用途：MuJoCo 逐 geom 读接触力；Isaac Lab merge_fixed_joints=False 后逐 prim 挂",
           "       ContactSensor。参数与用法见 docs/xhand1-tactile-sim-params.md -->"]

    if with_visual:
        out += ['  <material name="tactile_point">',
                '    <color rgba="1.0 0.35 0.05 1.0"/>',
                '  </material>']

    total = 0
    for side in SIDES:
        for finger in FINGERS:
            pts = load_points(json_dir / points_file(side, finger))
            parent = PARENT_LINK[finger].format(side=side)
            if len(pts) != 120:
                raise SystemExit(f"!! {side}/{finger} 测点数 {len(pts)} ≠ 120")

            offsets = [(0.0, 0.0, 0.0)] * len(pts)
            if proud_mm:
                stl = PKG_ROOT / "meshes" / "nero" / f"{side}_hand" / PARENT_MESH[finger].format(side=side)
                nrm = surface_normals(stl, [(x, y, z) for _, x, y, z in pts])
                offsets = [tuple(v * proud_mm / 1000.0) for v in nrm]

            for (idx, x, y, z), (ox, oy, oz) in zip(pts, offsets):
                name = f"{side}_hand_{finger}_tac_p{idx:03d}"
                xyz = f"{fmt((x / 1000.0) + ox)} {fmt((y / 1000.0) + oy)} {fmt((z / 1000.0) + oz)}"
                out.append(f'  <link name="{name}">')
                if density is not None:
                    vol = 4.0 / 3.0 * math.pi * r ** 3
                    m = density * vol
                    I = 0.4 * m * r * r
                    if I <= 1e-15:
                        raise SystemExit(
                            f"!! 惯量 {I:.3g} ≤ 1e-15，MuJoCo 会拒收（mjMINVAL 下限）；"
                            f"请加大 --radius 或 --density")
                    out += ['    <inertial>',
                            f'      <mass value="{fmt(m)}"/>',
                            f'      <inertia ixx="{fmt(I)}" ixy="0" ixz="0"'
                            f' iyy="{fmt(I)}" iyz="0" izz="{fmt(I)}"/>',
                            '    </inertial>']
                if with_visual:
                    out += ['    <visual>',
                            f'      <origin xyz="{xyz}" rpy="0 0 0"/>',
                            f'      <geometry><sphere radius="{fmt(r)}"/></geometry>',
                            '      <material name="tactile_point"/>',
                            '    </visual>']
                out += ['    <collision name="tac_{}_{}_p{:03d}">'.format(side, finger, idx),
                        f'      <origin xyz="{xyz}" rpy="0 0 0"/>',
                        f'      <geometry><sphere radius="{fmt(r)}"/></geometry>',
                        '    </collision>',
                        '  </link>',
                        '',
                        f'  <joint name="{side}_hand_{finger}_tac_joint_p{idx:03d}" type="fixed">',
                        f'    <parent link="{parent}"/>',
                        f'    <child link="{name}"/>',
                        '  </joint>',
                        '']
                total += 1
            out.append('')
    out.append(END)
    print(f"   生成 {total} 个测点 link（{len(SIDES) * len(FINGERS)} 指 × 120 点）")
    return "\n".join(out)


def strip_block(text: str) -> str:
    """删掉触觉块，并把两侧空行归一成 `\n\n` —— 保证「剥离→重建」字节可复现。"""
    new = re.sub(r"\n*[ \t]*<!-- TACTILE-BEGIN.*?<!-- TACTILE-END -->\n*", "\n\n", text, flags=re.S)
    if new == text and "TACTILE-BEGIN" in text:
        raise SystemExit("!! 找到 TACTILE-BEGIN 但没能完整剥离，请手工检查")
    return new


# --------------------------------------------------------------------------- #
def main(argv=None):
    ap = argparse.ArgumentParser(description="把 XHAND1 触觉测点阵内嵌进 URDF")
    ap.add_argument("--urdf", type=Path, default=DEFAULT_URDF)
    ap.add_argument("--json-dir", type=Path, default=PKG_ROOT / "config" / "tactile_points")
    ap.add_argument("--radius", type=float, default=0.5, help="探针球半径 mm（默认 0.5）")
    ap.add_argument("--proud", type=float, default=0.0, help="沿表面法线外凸 mm（默认 0）")
    ap.add_argument("--density", type=float, default=None,
                    help="探针球密度 kg/m³；给了就写显式 <inertial>（如 1100 = 触觉皮实测密度）。"
                         "不给则省略 inertial，由仿真器按几何推导")
    ap.add_argument("--no-visual", action="store_true", help="不写 visual 球（RViz 减负）")
    ap.add_argument("--remove-tactile", action="store_true", help="删掉已生成的块，还原厂商文件")
    ap.add_argument("--dry-run", action="store_true", help="只统计，不写文件")
    args = ap.parse_args(argv)

    text = args.urdf.read_text(encoding="utf-8")
    had = "TACTILE-BEGIN" in text
    base = strip_block(text) if had else text

    if args.remove_tactile:
        if not had:
            print("本来就没有触觉块，无需还原")
            return 0
        if not args.dry_run:
            args.urdf.write_text(base, encoding="utf-8")
        print(f"已移除触觉块，文件回到厂商版本（{len(base.splitlines())} 行）")
        return 0

    if had:
        print("检测到已有触觉块，先剥离再重建（幂等）")
    block = build_block(args.json_dir, args.radius, args.proud, args.density, not args.no_visual)

    if base.count("</robot>") != 1:
        raise SystemExit(f"!! URDF 里 </robot> 出现 {base.count('</robot>')} 次，预期 1 次")
    # 与 strip_block 的归一化配套：块前留一个空行，块后留一个空行
    new = base.replace("</robot>", block + "\n\n</robot>")

    n_link = new.count('<link name=')
    n_joint = new.count('<joint name=')
    print(f"   结果：{n_link} link / {n_joint} joint，{len(new.splitlines())} 行"
          f"（原 {len(text.splitlines())} 行）")

    if args.dry_run:
        print("   --dry-run：未写文件")
        return 0
    args.urdf.write_text(new, encoding="utf-8")
    print(f"   已写入 {args.urdf}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
